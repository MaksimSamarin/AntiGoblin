const fs = require("fs");
const os = require("os");
const path = require("path");
const { spawnSync } = require("child_process");

const repo = path.resolve(__dirname, "..");
const worker = path.join(repo, "ui/xkeen-manager/backend/subscription-refresh.js");
const candidateWorker = path.join(repo, "ui/xkeen-manager/backend/subscription-candidate.js");
const app = path.join(repo, "ui/xkeen-manager/app.js");
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "antigoblin-auto-refresh-"));

function baseState() {
  return {
    activeProfileId: "profile-1",
    profiles: [{
      id: "profile-1",
      activeProxyId: "active",
      subscriptions: [{ id: "sub-1", name: "Lab", url: "https://example.test/sub", autoRefresh: true, autoRefreshIntervalHours: 6, lastFetched: 0 }],
      proxies: [
        { id: "active", name: "Active", source: "sub-1", config: { protocol: "vless", address: "active.example", port: 443, uuid: "00000000-0000-0000-0000-000000000001" } },
        { id: "removed", name: "Removed", source: "sub-1", config: { protocol: "vless", address: "removed.example", port: 443, uuid: "00000000-0000-0000-0000-000000000002" } }
      ]
    }]
  };
}

function run(state, job) {
  const statePath = path.join(tmp, "state.json");
  const jobsPath = path.join(tmp, "jobs.ndjson");
  const outPath = path.join(tmp, "out.json");
  fs.writeFileSync(statePath, JSON.stringify(state));
  fs.writeFileSync(jobsPath, JSON.stringify(job) + "\n");
  const result = spawnSync(process.execPath, [worker, statePath, jobsPath, outPath, app], { encoding: "utf8" });
  if (result.status !== 0) throw new Error(result.stderr || result.stdout);
  return JSON.parse(fs.readFileSync(outPath, "utf8"));
}

const body = [
  "vless://00000000-0000-0000-0000-000000000001@active.example:443?security=none#Active",
  "vless://00000000-0000-0000-0000-000000000003@new.example:8443?security=none#New",
  "vless://00000000-0000-0000-0000-000000000003@new.example:8443?security=none#Duplicate"
].join("\n");
let state = run(baseState(), { profileId: "profile-1", subId: "sub-1", now: 1000, ok: true, bodyBase64: Buffer.from(body).toString("base64") });
let profile = state.profiles[0];
if (profile.activeProxyId !== "active") throw new Error("active proxy id changed");
if (!profile.proxies.some((item) => item.id === "active")) throw new Error("active proxy was not preserved");
if (!profile.proxies.some((item) => item.config.address === "new.example")) throw new Error("new proxy was not added");
if (profile.proxies.filter((item) => item.config.address === "new.example").length !== 1) throw new Error("duplicate subscription key was retained");
if (profile.proxies.some((item) => item.id === "removed")) throw new Error("removed inactive proxy was retained");
if (profile.subscriptions[0].lastRefreshStats.added !== 1 || profile.subscriptions[0].lastRefreshStats.removed !== 1) throw new Error("refresh stats incorrect");

state = run(baseState(), { profileId: "profile-1", subId: "sub-1", now: 2000, ok: true, bodyBase64: Buffer.from(body.split("\n")[1]).toString("base64") });
profile = state.profiles[0];
const staleActive = profile.proxies.find((item) => item.id === "active");
if (!staleActive?.stale) throw new Error("removed active key was not preserved as stale");
if (profile.activeProxyId !== "active") throw new Error("active key switched without verification");

const failedBefore = baseState();
state = run(failedBefore, { profileId: "profile-1", subId: "sub-1", now: 3000, ok: false, error: "fetch failed" });
profile = state.profiles[0];
if (profile.proxies.length !== failedBefore.profiles[0].proxies.length) throw new Error("failed refresh changed proxy list");
if (profile.subscriptions[0].lastError !== "fetch failed") throw new Error("failed refresh error not recorded");

const candidateStatePath = path.join(tmp, "candidate-state.json");
const candidateDir = path.join(tmp, "candidate");
fs.mkdirSync(candidateDir);
fs.writeFileSync(candidateStatePath, JSON.stringify(baseState()));
const candidateRun = spawnSync(process.execPath, [candidateWorker, candidateStatePath, "active", candidateDir, app], { encoding: "utf8" });
if (candidateRun.status !== 0) throw new Error(candidateRun.stderr || candidateRun.stdout);
const candidate = JSON.parse(fs.readFileSync(path.join(candidateDir, "candidate.json"), "utf8"));
const outbounds = JSON.parse(fs.readFileSync(path.join(candidateDir, "outbounds.json"), "utf8"));
if (candidate.protocol !== "vless") throw new Error("candidate protocol missing");
if (!outbounds.outbounds.some((item) => item.tag === "vless-reality")) throw new Error("candidate outbounds not generated by app builder");

const hy2State = baseState();
hy2State.profiles[0].proxies.push({
  id: "hy2",
  name: "HY2",
  source: "sub-1",
  config: { protocol: "hysteria2", address: "hy2.example", port: 443, password: "secret", serverName: "hy2.example", insecure: false }
});
fs.writeFileSync(candidateStatePath, JSON.stringify(hy2State));
const hy2Dir = path.join(tmp, "candidate-hy2");
fs.mkdirSync(hy2Dir);
const hy2Run = spawnSync(process.execPath, [candidateWorker, candidateStatePath, "hy2", hy2Dir, app], { encoding: "utf8" });
if (hy2Run.status !== 0) throw new Error(hy2Run.stderr || hy2Run.stdout);
const hy2Candidate = JSON.parse(fs.readFileSync(path.join(hy2Dir, "candidate.json"), "utf8"));
const singbox = JSON.parse(fs.readFileSync(path.join(hy2Dir, "singbox.json"), "utf8"));
if (hy2Candidate.protocol !== "hysteria2") throw new Error("HY2 candidate protocol missing");
if (!singbox.outbounds.some((item) => item.type === "hysteria2")) throw new Error("HY2 candidate sing-box config missing");

fs.rmSync(tmp, { recursive: true, force: true });
console.log("PASS: scheduled refresh merges safely and candidate configs use the browser builders");
